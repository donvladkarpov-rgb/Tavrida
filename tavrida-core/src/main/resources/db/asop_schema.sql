    CONSTRAINT pk_routes PRIMARY KEY (ROUTE_ID),
    CONSTRAINT fk_routes_organizer FOREIGN KEY (ORGANIZER_ID) REFERENCES ASOP_ORGANIZERS (ORGANIZER_ID),
