CREATE TABLE ASOP_TRANSPORT_STOPS
(
    STOP_ID      UUID         NOT NULL,
    FARE_ZONE_ID UUID,
    STOP_CODE    VARCHAR(20)  NOT NULL,
    STOP_NAME    VARCHAR(200) NOT NULL,
    STOP_ADDRESS VARCHAR(500),
    ZONE_POLYGON GEOGRAPHY(POLYGON, 4326),
    DESCRIPTION  TEXT,
